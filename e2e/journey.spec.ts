import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
test('register, configure, log, reload, edit and delete through Angular', async ({ page }) => {
  const errors: string[] = [];
  const email = `browser-${randomUUID()}@example.test`;
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/register');
  await page.getByLabel('Display name').fill('Growth Tester');
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-password-4912');
  await page.getByRole('button', { name: 'Create your account' }).click();
  await expect(page.getByRole('heading', { name: 'Keep growing, Growth Tester' })).toBeVisible();
  await expect(page.getByText('A fresh canvas')).toBeVisible();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-password-4912');
  await page.getByRole('button', { name: 'Sign in', exact: false }).click();
  await expect(page.getByRole('heading', { name: 'Keep growing' })).toBeVisible();
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Daily goal in minutes').fill('120');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('status')).toContainText('Settings saved');
  await page.getByRole('link', { name: 'Log activity', exact: true }).click();
  await page.getByRole('button', { name: 'Save activity' }).click();
  await expect(page.getByRole('alert')).toContainText('Choose a date and category');
  await page.getByLabel('What did you work on?').fill('Learned ArgoCD');
  await page.getByLabel('Category', { exact: true }).selectOption({ label: 'DevOps & Cloud' });
  await page.getByLabel('Hours', { exact: true }).fill('2');
  await page.getByLabel('Minutes', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Save activity' }).click();
  await expect(page.getByRole('heading', { name: 'Keep growing' })).toBeVisible();
  await expect(page.getByText('Learned ArgoCD', { exact: true })).toBeVisible();
  await expect(page.locator('.metric').first()).toContainText('100');
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.reload();
  await expect(page.getByText('Learned ArgoCD', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Activity history', exact: true }).click();
  await page.getByRole('link', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Hours', { exact: true }).fill('0');
  await page.getByLabel('Minutes', { exact: true }).fill('12');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.locator('.metric').first()).toContainText('10');
  await page.getByRole('link', { name: 'Activity history', exact: true }).click();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('button', { name: 'Delete activity', exact: true }).click();
  await expect(page.getByText('No activities found')).toBeVisible();
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await expect(page.locator('.metric').first()).toContainText('0m');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'Keep growing' })).toBeVisible();
  await expect
    .poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    .toBe(true);
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});
